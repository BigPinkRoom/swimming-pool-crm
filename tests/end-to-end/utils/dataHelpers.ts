export function generatePhoneNumber() {
  const randomNumberSuffix = fakerRu.string.numeric("##########");
  const phone = `+7 (9${randomNumberSuffix.substring(
    1,
    3
  )}) ${randomNumberSuffix.substring(3, 6)}-${randomNumberSuffix.substring(
    6,
    8
  )}-${randomNumberSuffix.substring(8, 10)}`;
  return phone;
}

export function getRandomValueFromArray<T>(array: T[]): T {
  const randomIndex = Math.floor(Math.random() * array.length);
  return array[randomIndex];
}
